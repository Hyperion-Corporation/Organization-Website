#!/usr/bin/env node
// Stages the repository's guide documents into <repo>/.guides-content for the
// "guides" docs-plugin instance (see ../docusaurus.config.ts).
//
// Why copy instead of pointing the plugin at the repository root: Docusaurus
// registers one MDX webpack rule per docs-plugin instance, keyed on that
// instance's content directory. When the guides instance's directory is the
// repository root, its rule also matches every file under docs/ — which the
// "default" instance already owns — so those files run through the MDX loader
// twice and each docs page renders its own compiled module source as prose
// ("export const frontMatter = {} ..."). `include`/`exclude` cannot prevent
// this; they filter which files become documents, not which files the loader
// rule matches. Staging the three guide files into a directory that contains
// nothing else keeps the two instances' content trees disjoint.
//
// The staging directory therefore sits at the repository root (.guides-content)
// rather than inside docs/website/: the "default" instance's content directory
// is docs/, so anything staged under docs/website/ would hit the mirror image of
// the same bug (the default instance's loader claiming the guide files).
//
// The copies are build artifacts (git-ignored): edit the sources listed below.
// docusaurus.config.ts maps each staged file back to its source for "Edit this
// page" links.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, '../../../');
const outputDir = path.resolve(repoRoot, '.guides-content');

// source (repo-relative) -> staged file name. `README.md` keeps that name so
// Docusaurus treats it as the section index at /guides/.
export const GUIDE_SOURCES = {
  'README.md': 'README.md',
  'git/CONTRIBUTING.md': 'CONTRIBUTING.md',
  '.agent/AGENTS.md': 'AGENTS.md',
};

const BANNER = (source) =>
  `<!-- Generated by docs/website/scripts/sync-guides.mjs from ${source}. Edit that file, not this copy. -->\n`;

function main() {
  mkdirSync(outputDir, { recursive: true });

  for (const [source, target] of Object.entries(GUIDE_SOURCES)) {
    const sourcePath = path.join(repoRoot, source);
    const targetPath = path.join(outputDir, target);
    const contents = readFileSync(sourcePath, 'utf8');
    writeFileSync(targetPath, BANNER(source) + contents);
  }

  console.log(`Staged ${Object.keys(GUIDE_SOURCES).length} guides into ${path.relative(repoRoot, outputDir)}/`);
}

main();
